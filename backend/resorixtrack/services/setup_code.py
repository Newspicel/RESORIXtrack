"""One-time setup code: proves that whoever runs the first-run wizard also controls the server.

Generated by `flask resorixtrack migrate` (i.e. on every container start) while no user exists, stored
as a SHA-256 hash in the settings table and printed to the server log. `flask resorixtrack setup-code`
prints a fresh one. Not needed once the first administrator exists.
"""

from __future__ import annotations

import hmac
import secrets

from ..extensions import db
from ..models import Setting, User
from ..security import token_hash

ALPHABET = "ABCDEFGHJKLMNPQRSTUVWXYZ23456789"  # no 0/O/1/I
KEY = "setup_code_hash"


def needed() -> bool:
    return (db.session.scalar(db.select(db.func.count(User.id))) or 0) == 0


def generate() -> str:
    code = "-".join("".join(secrets.choice(ALPHABET) for _ in range(4)) for _ in range(3))
    row = db.session.get(Setting, KEY)
    if row is None:
        db.session.add(Setting(key=KEY, value=token_hash(code)))
    else:
        row.value = token_hash(code)
    db.session.commit()
    return code


def ensure() -> str | None:
    """Create a code if none exists yet; returns the plain code only when newly generated."""
    if not needed():
        return None
    row = db.session.get(Setting, KEY)
    if row is not None and row.value:
        return None
    return generate()


def verify(code: str) -> bool:
    row = db.session.get(Setting, KEY)
    if row is None or not row.value or not code:
        return False
    normalized = code.strip().upper().replace(" ", "")
    return hmac.compare_digest(token_hash(normalized), str(row.value))


def clear() -> None:
    row = db.session.get(Setting, KEY)
    if row is not None:
        db.session.delete(row)


def banner(code: str) -> str:
    return ("\n" + "=" * 72 + "\n"
            "  RESORIXtrack first-run setup\n"
            "  Open the web app and enter this one-time setup code when asked:\n\n"
            f"      {code}\n\n"
            "  (regenerate with: flask resorixtrack setup-code)\n" + "=" * 72)
